type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends string
    ? string
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Copy = Widen<typeof fr>;

export function getCopy(language: Language): Copy {
  return language === "fr" ? fr : en;
}

export function getQuoteStatusLabel(
  status: "pending" | "followed-up" | "signed" | "lost",
  copy: Copy,
) {
  switch (status) {
    case "pending":
      return copy.forms.waiting;
    case "followed-up":
      return copy.forms.followedUp;
    case "signed":
      return copy.forms.signed;
    case "lost":
      return copy.forms.lost;
  }
}

export function formatCurrency(amount: number, language: Language) {
  return new Intl.NumberFormat(language === "fr" ? "fr-FR" : "en-IE", {
    style: "currency",
    currency: "EUR",
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(amount);
}
